"""``requirements/*.txt`` must be exactly what pyproject says, because the CE images install them.

The judge runs from a repo MOUNTED into the CE image, so nothing installs the package's own declared
deps at container-build time -- only the ``-r requirements/<hw>.txt`` install does (see
containers/cluster/ce-images/judge-agent-amd/Dockerfile and .../judge-agent-cuda/Dockerfile, each installing exactly one
requirements/<hw>.txt and never the project itself). Those files therefore have to exist; what they
must NOT be is a second hand-maintained copy of the dependency list, because a copy drifts. They are
generated by :mod:`scripts.sync_requirements`, and this module is the gate on that.

The drift it caught when the generator landed was live, not theoretical: amd.txt and nvidia.txt
carried a bare ``pythran`` against pyproject's ``pythran==0.18.1`` -- the pin that exists because
0.19.0 turns subset_sum into a >600 s hang, then a SIG11 -- and neither declared ``ordered-set``,
which every dace import needs. The CE images installed exactly what those files said.

Stdlib only: pyproject is read with tomllib, never through setuptools.
"""

import pathlib
import re
import sys
import tomllib
import pytest

from hpcagent_bench import paths

sys.path.insert(0, str(paths.ROOT / "scripts"))  # the generator is a script, not an installed module
import sync_requirements  # noqa: E402  (needs the path above)

REQUIREMENTS_DIR = paths.ROOT / "requirements"
PYPROJECT = paths.ROOT / "pyproject.toml"

#: Files under requirements/ that :mod:`scripts.sync_requirements` deliberately does not own.
#: optional.txt is a two-package convenience split (apache-tvm + mpi4py, the baselines with platform
#: install friction) that matches no single extra, so there is nothing to generate it from.
HAND_MAINTAINED = frozenset({"requirements/optional.txt"})

#: Declared names that are intentionally never installed from a requirements file. dace is
#: git-cloned editable in the Dockerfile, so it has no PyPI-style entry to match; exempted here, not
#: silently dropped, so the exemption is visible and a REAL new dependency named "dace" would still
#: need a second look.
DACE_EXEMPT = frozenset({"dace"})


def normalize(name: str) -> str:
    """PEP 503 normalization: lowercase, runs of ``-_.`` collapse to one ``-``."""
    return re.sub(r"[-_.]+", "-", name).lower()


def package_name(requirement: str) -> str:
    """The bare distribution name out of a requirement spec, dropping extras/version/markers.

    ``jax[cuda12]``, ``ordered-set >= 4.0.0`` and ``numpy>=2,<3`` all yield just the leading
    name token; a line with no name (blank after stripping) yields "".
    """
    requirement = requirement.split(";", 1)[0]  # drop the environment marker, if any
    match = re.match(r"[A-Za-z0-9][A-Za-z0-9._-]*", requirement.strip())
    return match.group(0) if match else ""


def project_dependencies(pyproject: pathlib.Path) -> list[str]:
    """``[project] dependencies`` out of pyproject.toml.

    tomllib, not setuptools: this test asserts what the file DECLARES, and building the metadata
    would let a backend default or a plugin supply a name the file itself does not.
    """
    return list(tomllib.loads(pyproject.read_text())["project"]["dependencies"])


def parse_requirements(path: pathlib.Path) -> frozenset[str]:
    """Normalized distribution names declared in a requirements.txt.

    Skips blank lines, ``#`` comments, and pip options (``--pre``, ``--no-binary=...``) -- none
    of those are a distribution name.
    """
    names = set()
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or line.startswith("-"):
            continue
        name = package_name(line)
        if name:
            names.add(normalize(name))
    return frozenset(names)


DEPENDENCIES = project_dependencies(PYPROJECT)


def test_dependencies_parse_to_the_known_deps():
    """Sanity check on the toml parse itself, independent of the assertions below -- if this list
    came back empty or truncated, the coverage test would pass for the wrong reason (nothing left
    to check)."""
    normalized = {normalize(package_name(r)) for r in DEPENDENCIES}
    assert {"numpy", "scipy", "jinja2", "sqlmodel", "cffi"} <= normalized
    assert len(DEPENDENCIES) >= 8


def test_package_name_strips_specifiers_extras_and_markers():
    cases = {
        "numpy>=2,<3": "numpy",
        "jax[cuda12]": "jax",
        "ordered-set >= 4.0.0": "ordered-set",
        "blake3": "blake3",
        'foo>=1; python_version<"3.11"': "foo",
    }
    for spec, expected in cases.items():
        assert package_name(spec) == expected


def test_normalize_follows_pep_503():
    assert normalize("ml_dtypes") == normalize("ml-dtypes") == "ml-dtypes"
    assert normalize("PyYAML") == "pyyaml"
    assert normalize("tree_sitter.language--pack") == "tree-sitter-language-pack"


def test_parse_requirements_skips_comments_and_pip_options(tmp_path):
    path = tmp_path / "req.txt"
    path.write_text("# a comment\n--pre\nnumpy>=2,<3\n\n--no-binary=mpi4py\nmpi4py\n")
    assert parse_requirements(path) == frozenset({"numpy", "mpi4py"})


def test_generated_requirements_are_in_sync_with_pyproject():
    """The real gate. A dependency edited in pyproject and not regenerated here would ship to the CE
    images as the OLD list, silently -- a container build is the only thing that would notice, hours
    later and on a different machine."""
    diffs = sync_requirements.check()
    assert not diffs, (
        "requirements/*.txt are stale against pyproject.toml. Run "
        "`python scripts/sync_requirements.py`.\n" + "\n".join(diffs)
    )


def test_self_referencing_extras_expand():
    """``cpu``/``nvidia``/``amd`` each pull the shared stack in as ``hpcagent_bench[frameworks]``. If
    that stopped expanding, the hardware files would ship the platform bits and none of the shared
    ones -- a short file that still looks plausible."""
    extras = tomllib.loads(PYPROJECT.read_text())["project"]["optional-dependencies"]
    resolved = sync_requirements.resolve("nvidia", extras)
    assert "hpcagent_bench[frameworks]" not in resolved
    assert "pythran==0.18.1" in resolved  # came from frameworks
    assert "cupy-cuda13x" in resolved  # came from nvidia itself


def test_a_cyclic_extra_is_rejected_rather_than_recursing():
    extras = {"a": ["hpcagent_bench[b]"], "b": ["hpcagent_bench[a]"]}
    with pytest.raises(ValueError, match="includes itself"):
        sync_requirements.resolve("a", extras)


def test_every_requirements_file_is_generated_or_declared_hand_maintained():
    """A new hand-written file under requirements/ is a new place for the list to drift. Adding one
    means either giving it an extra to generate from, or saying here why it has none."""
    on_disk = {str(p.relative_to(paths.ROOT)) for p in REQUIREMENTS_DIR.glob("*.txt")}
    on_disk.add("requirements.txt")
    unaccounted = sorted(on_disk - set(sync_requirements.GENERATED) - HAND_MAINTAINED)
    assert not unaccounted, f"requirements files that are neither generated nor declared hand-maintained: {unaccounted}"


def test_dependencies_are_a_subset_of_amd_and_nvidia_requirements():
    """What the generation is FOR: every runtime import pyproject declares must be preinstalled in
    the hardware requirements file the CE image actually installs, since the judge never installs
    the project inside the mounted-repo container. Generation makes this hold by construction --
    this asserts the construction, i.e. that those two files still carry the core deps at all."""
    declared = {normalize(package_name(r)) for r in DEPENDENCIES} - DACE_EXEMPT
    for filename in ("amd.txt", "nvidia.txt"):
        req_names = parse_requirements(REQUIREMENTS_DIR / filename)
        missing = sorted(declared - req_names)
        assert not missing, (
            f"[project] dependencies missing from requirements/{filename}: {missing} "
            f"-- the judge mounts the repo into the CE image and never installs the project, "
            f"so a name absent here is a ModuleNotFoundError inside that container"
        )
